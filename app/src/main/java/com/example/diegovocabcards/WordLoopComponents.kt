@Composable
internal fun Section(content: @Composable ColumnScope.() -> Unit) {
    Card(colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)) {
        Column(Modifier.fillMaxWidth().padding(14.dp), verticalArrangement = Arrangement.spacedBy(6.dp), content = content)
    }
}

@Composable
internal fun SummaryRow(label: String, count: Int) {
    Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
        Text(label)
        Text(count.toString(), style = MaterialTheme.typography.titleMedium)
    }
}

@Composable
internal fun detailSummary(example: String, synonyms: String): String {
    val examples = example.lines().count { it.isNotBlank() }
    val words = synonyms.split(',').count { it.isNotBlank() }
    return listOf(pluralStringResource(R.plurals.examples, examples, examples),
        pluralStringResource(R.plurals.synonyms, words, words)).joinToString(" · ")
}

@Composable
internal fun DetailPage(title: String, onDone: () -> Unit, content: @Composable ColumnScope.() -> Unit) {
    Dialog(onDismissRequest = onDone, properties = DialogProperties(usePlatformDefaultWidth = false, decorFitsSystemWindows = false)) {
        Surface(color = MaterialTheme.colorScheme.background, modifier = Modifier.fillMaxSize()) {
            val view = androidx.compose.ui.platform.LocalView.current
            val darkIcons = androidx.compose.material3.MaterialTheme.colorScheme.background == androidx.compose.ui.graphics.Color(0xFFF6F8FF)
            androidx.compose.runtime.SideEffect {
                (view.parent as? androidx.compose.ui.window.DialogWindowProvider)?.window?.let { window ->
                    androidx.core.view.WindowCompat.getInsetsController(window, view).apply {
                        isAppearanceLightStatusBars = darkIcons
                        isAppearanceLightNavigationBars = darkIcons
                    }
                }
            }
            Column(Modifier.fillMaxSize().safeDrawingPadding().imePadding().padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text(title, style = MaterialTheme.typography.headlineMedium)
                Column(Modifier.weight(1f).verticalScroll(rememberScrollState()),
                    verticalArrangement = Arrangement.spacedBy(10.dp), content = content)
                Button(onClick = onDone, modifier = Modifier.fillMaxWidth()) { Text(stringResource(R.string.ui_done)) }
            }
        }
    }
}

internal fun sourceDisplay(line: String): String = when (line) {
    GEMINI_IPA -> "Suggested by Gemini"
    MANUAL_IPA -> "Entered manually"
    GEMINI_TRANSLATION -> "Translation suggested by Gemini Nano"
    GEMINI_SYNONYMS -> "Synonyms suggested by Gemini Nano"
    GOOGLE_TRANSLATION.lineSequence().first() -> "Translated by Google Translate"
    GENERATED_WITH_NANO -> "Generated by Gemini Nano"
    "Contenido seleccionado y editable por el usuario." -> "Content selected and editable by the user."
    else -> line.replace("Colaboradores de Wiktionary", "Wiktionary contributors")
        .replace("Wiktionary vía Free Dictionary API", "Wiktionary via Free Dictionary API")
}

internal fun languageName(code: String) = if (code == "ja") "Japanese" else "Spanish"

internal fun List<com.example.diegovocabcards.data.Card>.translationLabel(): String =
    map { it.language }.distinct().let { if (it.size > 1) "Translation" else languageName(it.firstOrNull() ?: "es") }
